export const normalizePrompt = (value: string): string => value.toLowerCase().replace(/[^a-z0-9\s]/g, "").replace(/\s+/g, " ").trim();
export function promptWarnings(prompt: string): string[] {
  const normalized = normalizePrompt(prompt);
  return WARNING_TERMS.filter((term) => normalized.includes(normalizePrompt(term)));
}
